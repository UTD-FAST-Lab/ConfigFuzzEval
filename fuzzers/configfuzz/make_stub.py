#!/usr/bin/env python3
"""Generates ConfigFuzz code for a benchmark from its rt_grammar.json.

rt_grammar.json uses ConfigFuzz's configuration grammar format, so ConfigFuzz's own
stub generator (stub_tools/stub, unchanged from the paper's artifact) is used to
produce the code. This script only wraps that code for this framework:

  lib <grammar>                  C source of the stub library that run.sh preloads.
                                 ConfigFuzz's generated main() becomes
                                 configfuzz_entry(), called by cf_hook.c in place of
                                 the program's main (ConfigFuzz's fuzz_main).
  printer <grammar>              C source of ConfigFuzz's printer (-p), which prints
                                 the command line an input decodes to. Used by
                                 coverage.py.
  seeds <grammar> <in> <out>     Copies the seeds, prefixed with option bytes that
                                 decode to "no option", so that each seed initially
                                 runs with the default command line.
"""

import contextlib
import io
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "stub_tools"))

from stub import build_main, build_printer, build_stub, build_zero  # noqa: E402

INCLUDES = """#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
"""

GENERATED_MAIN = "int main (int argc, char **argv) {"
SHM_FILE = 'sprintf(filename, "/dev/shm/optfuzzer.%d", getpid());'
GET_ARGS = "argv = configfuzz_get_args(&argc, argv);"


def load_grammar(path):
    with open(path) as f:
        grammar = json.load(f)
    # ConfigFuzz splits cmdline on single spaces; collapse repeated spaces so they
    # do not become empty arguments.
    grammar["cmdline"] = " ".join(grammar["cmdline"].split())
    return grammar


def generated(func, *args):
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        func(*args)
    return out.getvalue()


def lib_source(grammar):
    if grammar["maxcombs"] == 0:
        code = generated(build_zero.build_zero, grammar)
    else:
        code = generated(build_stub.build_stub, grammar) + generated(build_main.build_main, grammar)
        # The data part of each input is written to /dev/shm and removed when main
        # returns. Also remove it when the program calls exit() instead, so files do
        # not pile up in /dev/shm over millions of executions.
        assert SHM_FILE in code
        code = code.replace(SHM_FILE, SHM_FILE + "\n    configfuzz_track_file(filename);")
        # For conflicting or unmet dependent options the generated stub returns no
        # command line (NULL), which made the program crash on argv and was reported
        # as a crash. Exit normally instead, as the invalid configuration would.
        assert GET_ARGS in code
        code = code.replace(GET_ARGS, GET_ARGS + "\n        if (!argv) exit(0);")
    assert GENERATED_MAIN in code
    code = code.replace(GENERATED_MAIN, "static int configfuzz_main(int argc, char **argv) {")
    return INCLUDES + """
extern char **environ;

typedef int (*configfuzz_main_fn)(int, char **, char **);
static configfuzz_main_fn configfuzz_real_main;

/* ConfigFuzz calls the program's renamed main fuzz_main. The generated stub passes
   option values as string literals (read-only memory); programs may modify their
   argv strings (pcre2test, bison and x264 do), which crashed them. Pass writable
   copies, as a normal command line would. */
static int fuzz_main(int argc, char **argv) {
    char **args = calloc(argc + 1, sizeof(char *));
    for (int i = 0; i < argc; i++)
        args[i] = strdup(argv[i]);
    return configfuzz_real_main(argc, args, environ);
}

static char configfuzz_file[256];

static void configfuzz_remove_file(void) {
    if (configfuzz_file[0])
        remove(configfuzz_file);
}

static void configfuzz_track_file(const char *filename) {
    snprintf(configfuzz_file, sizeof(configfuzz_file), "%s", filename);
    atexit(configfuzz_remove_file);
}

/* ---- generated by ConfigFuzz ---- */
""" + code + """
/* ---- end of generated code ---- */

int configfuzz_entry(int argc, char **argv, configfuzz_main_fn real_main) {
    configfuzz_real_main = real_main;
    return configfuzz_main(argc, argv);
}
"""


def printer_source(grammar):
    return INCLUDES + generated(build_stub.build_stub, grammar) + generated(build_printer.build_printer)


def header(grammar):
    """Option and setting bytes that ConfigFuzz's stub reads before the data."""
    opts_num = len(grammar["options"])
    params_num = len([o for o in grammar["options"] if o["type"] != "bool"])
    bufsize = grammar["strmax"] + 1 if "strmax" in grammar else build_stub.STR_MAXLEN + 1
    # Same modulus as build_stub.write_options; values >= opts_num select no option.
    modulus = opts_num + max(opts_num // (build_stub.NOT_PRESENT_PROB - 1), 1)
    no_option = next((v for v in range(256) if v % modulus >= opts_num), 0)
    return bytes([no_option]) * grammar["maxcombs"] + bytes(params_num * bufsize)


def write_seeds(grammar, seed_dir, out_dir):
    prefix = header(grammar) if grammar["maxcombs"] > 0 else b""
    os.makedirs(out_dir, exist_ok=True)
    for name in sorted(os.listdir(seed_dir)):
        path = os.path.join(seed_dir, name)
        if os.path.isfile(path):
            with open(path, "rb") as f, open(os.path.join(out_dir, name), "wb") as out:
                out.write(prefix + f.read())


def main():
    mode, grammar = sys.argv[1], load_grammar(sys.argv[2])
    if mode == "lib":
        print(lib_source(grammar))
    elif mode == "printer":
        print(printer_source(grammar))
    elif mode == "seeds":
        write_seeds(grammar, sys.argv[3], sys.argv[4])
    else:
        sys.exit(f"unknown mode: {mode}")


if __name__ == "__main__":
    main()
