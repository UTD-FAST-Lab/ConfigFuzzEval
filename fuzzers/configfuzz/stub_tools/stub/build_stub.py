import json
import logging

from stub import grammar_utils
from stub.code_builder import CodeBuilder

# Maximum string length. Should be one less than a multiple of 4.
STR_MAXLEN = 19
# For each of the k(=maxcombs) possible options per set, there is a 1/NOTPRESENT_PROB probability of no option being
# chosen.
NOT_PRESENT_PROB = 5


def build_stub(grammar: json, return_str: bool = False):
    builder = CodeBuilder()
    write_dec_and_def(builder)
    write_var_setups(builder, grammar)
    write_options(builder, grammar)
    write_close_out(builder)
    if return_str:
        return builder.code()
    else:
        print(builder.code())


# Stub declaration and definition.
def write_dec_and_def(builder: CodeBuilder):
    builder.write_line('static char **configfuzz_get_args(int *, char **);', new_line=2)
    builder.write_line('static char **configfuzz_get_args(int *p_argc, char **argv) {')


# Local variables that are used throughout the stub.
def write_var_setups(builder: CodeBuilder, grammar: json):
    # The command line for fuzzing the program.
    # '$inopts' represents configurations generated by ConfigFuzz, and `$INPUTFILE` represents the path to input file.
    cmdline = grammar_utils.cmd_line(grammar)
    assert '$inopts' in cmdline
    assert '$INPUTFILE' in cmdline or '$STDIN' in cmdline
    # Number of args not generated by ConfigFuzz, minus the 2 from input `argv`.
    fixed_args_num = len([c for c in cmdline if c != '$inopts' and c != '$STDIN'])
    # Number of options that are potentially generated by ConfigFuzz.
    opts_num = grammar_utils.opts_num(grammar)
    # Non-bool options have parameters.
    param_opts_num = len([y for y in grammar['options'] if y['type'] != 'bool'])
    # A parameter takes 1 arg if it's connected by space, like `-f flv`.
    param_opts_size = param_opts_num if grammar_utils.is_space_connected(grammar) else 0
    # Stores the command-line args like `argv`. Its size is number of args.
    builder.write_line(
        f'static char *cmdargs[{fixed_args_num + grammar["maxcombs"] * (2 if grammar_utils.is_space_connected(grammar) else 1) + 2}];',
        indent=1)
    # Stores number of command-line args like `argc`.
    builder.write_line('int argspos = 0;', indent=1)
    # Copy first 2 args from input.
    builder.write_line('cmdargs[argspos++] = argv[0];', indent=1)
    builder.write_line('char *filename = argv[1];', indent=1)
    # Max number of options generated in one configuration.
    builder.write_line(f'int maxcombs = {grammar["maxcombs"]};', indent=1)
    # Bytes that represent options (option bytes).
    builder.write_line(f'unsigned char optsbmp[maxcombs];', indent=1)
    bufsize = grammar['strmax'] + 1 if 'strmax' in grammar else STR_MAXLEN + 1
    assert bufsize % 4 == 0
    # Bytes that represent parameters (setting bytes).
    builder.write_line(f'static unsigned char optparams[{param_opts_num}][{bufsize}];', indent=1)

    write_file_ops(builder)

    builder.write_line(f'static unsigned char optstrs[{param_opts_num}][40];', indent=1)
    enabled_bmp_size = (opts_num // 8) if opts_num % 8 == 0 else (opts_num // 8) + 1
    # Stores generated options, so that depend and conflict can be processed at the end.
    builder.write_line(f'unsigned char enabledoptsbmp[{enabled_bmp_size}];', indent=1)
    builder.write_line(f'for (int i = 0; i < {enabled_bmp_size}; i++) enabledoptsbmp[i] = 0;', indent=1)


# Reads option bytes and setting bytes from the input.
def write_file_ops(builder: CodeBuilder):
    file_op = '''
    FILE *fp;
    if ((fp = fopen(filename, "rb")) != NULL) {
        fseek(fp, 0L, SEEK_END);
        int size = ftell(fp);
        rewind(fp);
        
        if (size < sizeof(optsbmp) + sizeof(optparams)) {
            fclose(fp);
            goto fuzz_option_end;
        }
        
        fread(optsbmp, 1, sizeof(optsbmp), fp);
        fread(optparams, 1, sizeof(optparams), fp);
        
        size = size - sizeof(optsbmp) - sizeof(optparams);
        unsigned char input[size];
        fread(input, 1, sizeof(input), fp);
        fclose(fp);

        fp = fopen(filename, "wb");
        fwrite(input, sizeof(input), 1, fp);
        fclose(fp);
    }
    '''
    builder.write_block(file_op)
    builder.write_new_line(1)


def write_options(builder: CodeBuilder, grammar: json):
    builder.write_line('for (int i = 0; i < maxcombs; i++) {', indent=1)
    # Stores value for opt byte.
    builder.write_line(f'unsigned char combopt = optsbmp[i];', indent=2)
    opts_num = grammar_utils.opts_num(grammar)
    # Calculates hash from opt byte.
    builder.write_line(f'combopt %= {opts_num + max(opts_num // (NOT_PRESENT_PROB - 1), 1)};', indent=2)
    # Stores value of param bytes.
    builder.write_line(f'unsigned int optparam;', indent=2)
    builder.write_line('switch(combopt) {', indent=2)
    # Index of option with param.
    i_optparams = 0
    cmdline = grammar_utils.cmd_line(grammar)
    for arg in cmdline:
        if arg == '$INPUTFILE':
            builder.write_line('cmdargs[argspos++] = filename;', 1)
        elif arg == '$STDIN':
            continue
        elif arg == '$inopts':
            for i in range(opts_num):
                # Command-line option.
                opt = grammar['options'][i]
                # Option's command-line arg string.
                opt_arg = opt['opt']
                builder.write_line(f'case {i}: {{', indent=2)
                # Update bitmap for enabled options.
                builder.write_line(f'enabledoptsbmp[{i // 8}] |= {2 ** (i % 8)};', indent=3)
                if opt['type'] == 'bool':
                    builder.write_line(f'cmdargs[argspos++] = "{opt_arg}";', 3)
                else:  # Options with params.
                    if opt['type'] == 'string':
                        assert 'size' in opt
                        assert opt['size'] <= STR_MAXLEN
                        builder.write_line(f'char *strval = optparams[{i_optparams}];', 3)
                        builder.write_line(f"strval[{opt['size']}] = '\\0';", 3)
                        if grammar_utils.is_space_connected(grammar):
                            builder.write_line(f'cmdargs[argspos++] = "{opt_arg}";', 3)
                            builder.write_line('cmdargs[argspos++] = strval;', 3)
                        else:
                            builder.write_line(
                                f'snprintf(optstrs[{i_optparams}], sizeof(optstrs[{i_optparams}]), "{opt_arg}{grammar["connector"]}%s", strval);',
                                3)
                            builder.write_line(f'cmdargs[argspos++] = optstrs[{i_optparams}];', 3)
                    else:  # choice, intnum and realnum options.
                        condense_buf(builder, 3, i_optparams)
                        if opt['type'] == 'choice':
                            # Calculates hash from config byte.
                            builder.write_line(f'optparam %= {len(opt["choices"])};', 3)
                            if grammar_utils.is_space_connected(grammar):
                                builder.write_line(f'cmdargs[argspos++] = "{opt_arg}";', 3)

                                def param_func(x):
                                    return x
                            else:
                                def param_func(x):
                                    return f'{opt_arg}{grammar["connector"]}{x}'
                            # First option gets an if.
                            builder.write_line(
                                f'if (optparam == 0) cmdargs[argspos++] = "{param_func(opt["choices"][0])}";', 3)
                            # Subsequent options get else ifs.
                            for j in range(1, len(opt['choices'])):
                                builder.write_line(
                                    f'else if (optparam == {j}) cmdargs[argspos++] = "{param_func(opt["choices"][j])}";',
                                    3)
                        elif opt['type'] == 'intnum':
                            rmin = opt['range'][0]
                            rmax = opt['range'][1]
                            rsize = rmax - rmin + 1
                            if rsize >= 2 ** 32:
                                logging.error('range too large')
                            builder.write_line(f'unsigned int val = {rmin} + optparam % {rsize};', 3)
                            if 'format' in opt:
                                fmtspec = opt['format']
                                if fmtspec == 'd' and rmin >= 0:
                                    fmtspec = 'u'
                            else:
                                fmtspec = 'd' if rmin < 0 else 'u'
                            if grammar_utils.is_space_connected(grammar):
                                builder.write_line(f'cmdargs[argspos++] = "{opt_arg}";', 3)
                                builder.write_line(
                                    f'snprintf(optstrs[{i_optparams}], sizeof(optstrs[{i_optparams}]), "%{fmtspec}", val);',
                                    3)
                            else:
                                builder.write_line(
                                    f'snprintf(optstrs[{i_optparams}], sizeof(optstrs[{i_optparams}]), "{opt_arg}{grammar["connector"]}%{fmtspec}", val);',
                                    3)
                            builder.write_line(f'cmdargs[argspos++] = optstrs[{i_optparams}];', 3)
                        elif opt['type'] == 'realnum':
                            rmin = opt['range'][0]
                            rmax = opt['range'][1]
                            rsize = rmax - rmin + 1
                            builder.write_line(f'double val = {rmin}.0 + fmod(*((float*)&optparam), {rsize}.0);', 3)
                            if grammar_utils.is_space_connected(grammar):
                                builder.write_line(f'cmdargs[argspos++] = "{opt_arg}";', 3)
                                builder.write_line(
                                    f'snprintf(optstrs[{i_optparams}], sizeof(optstrs[{i_optparams}]), "%10.3f", val);',
                                    3)
                            else:
                                builder.write_line(
                                    f'snprintf(optstrs[{i_optparams}], sizeof(optstrs[{i_optparams}]), "{opt_arg}{grammar["connector"]}%10.3f", val);',
                                    3)
                            builder.write_line(f'cmdargs[argspos++] = optstrs[{i_optparams}];', 3)
                    i_optparams += 1
                builder.write_line('break; }', 3)
            builder.write_line('default:', 2)
            builder.write_line('break;', 3)
            builder.write_line('}', 2)
            builder.write_line('}', 1)
        else:
            builder.write_line(f'cmdargs[argspos++] = "{arg}";', 1)

    opt2num = {grammar['options'][i]['opt']: i for i in range(opts_num)}
    builder.write_line('/* conflict */', 1)
    # If there are conflict options, exit directly.
    # TODO: Is this needed? Invalid configuration will exit the program anyway.
    for conf_pair in grammar['conflict']:
        # try:
        checkexprs = []
        for conf_opt in conf_pair:
            i, b = (opt2num[conf_opt]) // 8, (opt2num[conf_opt]) % 8
            checkexprs.append(f'enabledoptsbmp[{i}] & {2 ** b}')
        builder.write_line(
            f'if ({checkexprs[0]} && {checkexprs[1]}) return NULL; /* {conf_pair[0]} and {conf_pair[1]} conflict */', 1)
        # except KeyError:
        #     print()
    # TODO: Is this needed? Invalid configuration will exit the program anyway.
    builder.write_line('/* depend */', 1)
    for dep in grammar['depend']:
        i, b = (opt2num[dep['opt']]) // 8, (opt2num[dep['opt']]) % 8
        optcheckexpr = f'enabledoptsbmp[{i}] & {2 ** b}'
        oncheckexprs = {}
        for on in dep['on']:
            i, b = (opt2num[on]) // 8, (opt2num[on]) % 8
            oncheckexprs[on] = f'enabledoptsbmp[{i}] & {2 ** b}'
        builder.write_line(f'if ({optcheckexpr}) {{ /* {dep["opt"]} dependency */', 1)
        for k, v in oncheckexprs.items():
            builder.write_line(f'if (!{v}) return NULL; /* on {k} */', 2)
        builder.write_line('}', 1)


def write_close_out(builder: CodeBuilder):
    builder.write_line('fuzz_option_end:')
    # Close out the function.
    close_out = '''
    cmdargs[argspos] = NULL;
    *p_argc = argspos;
    return cmdargs;
} 
    '''
    builder.write_block(close_out)


# Write code to condense a buffer (of arbitrary multiple-of-4 size) to an unsigned int.
# Done by turning it into a sequence of ints and adding them all together.
def condense_buf(builder: CodeBuilder, indent: int, param_index: int) -> None:
    builder.write_line('optparam = 0;', indent)
    builder.write_line(f'for (int j = 0; j < sizeof(optparams[{param_index}]); j++) {{', indent)
    # Converts byte array to int.
    builder.write_line(f'optparam += optparams[{param_index}][j] << (8 * j);', indent + 1)
    builder.write_line('}', indent)
